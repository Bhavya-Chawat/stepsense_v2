import { useState } from 'react';
import { useNavigate } from 'react-router-dom';
import type { SessionSummary } from '@stepsense/types';
import { COLORS } from '@stepsense/design-tokens';
import { Sparkles, FileText, Download, Share2, RefreshCw } from 'lucide-react';
import { generateAiReport } from '../lib/groq';
import ReactMarkdown from 'react-markdown';
import remarkGfm from 'remark-gfm';
import { isDemoModeEnabled } from '../lib/mockData';
import { createSupabaseClient } from '@stepsense/supabase-client';

const supabaseUrl = import.meta.env.VITE_SUPABASE_URL || '';
const supabaseKey = import.meta.env.VITE_SUPABASE_ANON_KEY || '';
const supabase = supabaseUrl && supabaseKey ? createSupabaseClient(supabaseUrl, supabaseKey) : null;

interface AIReportCardProps {
  summary: SessionSummary | null;
  depth: 'basic' | 'clinical';
}

export function AIReportCard({ summary, depth }: AIReportCardProps) {
  const navigate = useNavigate();
  const [isGenerating, setIsGenerating] = useState(false);
  const [localReports, setLocalReports] = useState<Record<string, string>>({});
  const [error, setError] = useState<string | null>(null);

  if (!summary) {
    return (
      <div className="bg-card rounded-lg border border-border p-6 text-center shadow-none-none">
        <p className="text-sm text-ink-secondary">No AI report data available.</p>
      </div>
    );
  }

  const s = summary as any;
  const dbReport = depth === 'clinical' ? summary.ai_report_doctor : summary.ai_report_consumer;
  const currentReport = localReports[depth] || dbReport;
  const hasReport = !!currentReport;

  const handleGenerateClick = async () => {
    setIsGenerating(true);
    setError(null);
    try {
      const result = await generateAiReport(summary, depth);
      setLocalReports(prev => ({ ...prev, [depth]: result }));

      // Save to Supabase if not in Demo Mode
      if (!isDemoModeEnabled() && supabase) {
        const columnToUpdate = depth === 'clinical' ? 'ai_report_doctor' : 'ai_report_consumer';
        await supabase
          .from('session_summary')
          .update({ [columnToUpdate]: result })
          .eq('session_id', summary.session_id); // Assumes the table maps by session_id
      }
    } catch (err: any) {
      setError(err.message || 'Generation failed');
    } finally {
      setIsGenerating(false);
    }
  };

  const handleExportPDF = () => {
    document.body.classList.add('print-ai-only');
    window.print();
    setTimeout(() => {
      document.body.classList.remove('print-ai-only');
    }, 500);
  };

  const handleShare = async () => {
    if (!currentReport) return;
    try {
      if (navigator.share) {
        await navigator.share({
          title: `StepSense AI Report - ${depth.toUpperCase()}`,
          text: currentReport,
        });
      } else {
        await navigator.clipboard.writeText(currentReport);
        alert('Report copied to clipboard!');
      }
    } catch (err) {
      console.error('Error sharing', err);
    }
  };

  return (
    <div className="bg-white rounded-xl border border-slate-200 p-6 shadow-none-none space-y-5 text-slate-800 ai-report-printable print:border-none print:p-0">
      <div className="flex justify-between items-center pb-3 border-b border-slate-100 print:border-b-2 print:border-slate-800 print:mb-4">
        <div>
          <h3 className="text-base font-bold font-sans text-accent-teal flex items-center space-x-2">
            <Sparkles size={16} className="print:hidden" />
            <span>StepSense AI Assessment</span>
            {isGenerating && <span className="w-2 h-2 rounded-full bg-accent-teal animate-ping print:hidden" />}
          </h3>
          <p className="text-[10px] text-slate-500 mt-1">Generated by StepSense Clinical Intelligence Engine</p>
        </div>
        <div className="print:hidden">
          <button
            onClick={handleGenerateClick}
            disabled={isGenerating}
            className={`px-4 py-2 text-xs font-bold rounded shadow-none transition-colors flex items-center space-x-2 ${
              isGenerating ? 'bg-slate-200 text-slate-400 cursor-not-allowed' : 'bg-accent-teal text-white hover:opacity-90'
            }`}
          >
            {isGenerating ? (
              <><RefreshCw size={14} className="animate-spin" /><span>Generating...</span></>
            ) : hasReport ? (
              <><RefreshCw size={14} /><span>Regenerate</span></>
            ) : (
              <><Sparkles size={14} /><span>Generate My Report</span></>
            )}
          </button>
        </div>
      </div>

      {error && (
        <div className="bg-red-50 text-red-600 p-3 rounded text-xs font-semibold print:hidden">
          {error}
        </div>
      )}

      {/* Summary Badges Header */}
      <div className="flex space-x-3 mb-2 print:hidden">
        <div className="flex-1 bg-slate-50 rounded border border-slate-200 p-3 flex items-center justify-between">
          <span className="text-[10px] font-semibold text-slate-500 uppercase tracking-wider">Avg Gait Score</span>
          <span className="text-sm font-bold text-accent-teal">{s?.gait_score ?? '-'}</span>
        </div>
        <div className="flex-1 bg-slate-50 rounded border border-slate-200 p-3 flex items-center justify-between">
          <span className="text-[10px] font-semibold text-slate-500 uppercase tracking-wider">Fatigue Profile</span>
          <span className="text-sm font-bold" style={{ color: summary.fatigue_bucket === 'Severe' ? COLORS.statusCritical : summary.fatigue_bucket === 'Moderate' ? COLORS.statusModerate : COLORS.statusGood }}>
            {summary.fatigue_bucket ?? 'Normal'}
          </span>
        </div>
        <div className="flex-1 bg-slate-50 rounded border border-slate-200 p-3 flex items-center justify-between">
          <span className="text-[10px] font-semibold text-slate-500 uppercase tracking-wider">Top Risk</span>
          <span className="text-sm font-bold truncate ml-2" style={{ color: COLORS.statusCritical }} title={s?.joint_strain_severity === 'HIGH' ? 'Joint Strain' : s?.fall_risk_score >= 60 ? 'Fall Risk' : 'None'}>
             {s?.joint_strain_severity === 'HIGH' ? 'Joint Strain' : s?.fall_risk_score >= 60 ? 'Fall Risk' : 'None'}
          </span>
        </div>
      </div>

      {hasReport ? (
        <div className="bg-slate-50 rounded-lg border border-slate-200 p-5 text-sm leading-relaxed text-slate-700 font-sans h-[300px] overflow-y-auto print:h-auto print:overflow-visible print:border-none print:bg-white print:p-0 print:text-black">
          <ReactMarkdown 
            remarkPlugins={[remarkGfm]}
            components={{
              h1: ({node, ...props}) => <h1 className="text-xl font-bold text-accent-teal mt-5 mb-3" {...props} />,
              h2: ({node, ...props}) => <h2 className="text-lg font-bold text-accent-teal mt-4 mb-2" {...props} />,
              h3: ({node, ...props}) => <h3 className="text-base font-bold text-slate-800 mt-3 mb-2" {...props} />,
              p: ({node, ...props}) => <p className="text-slate-700 leading-relaxed mb-3" {...props} />,
              strong: ({node, ...props}) => <strong className="font-bold text-slate-900" {...props} />,
              ul: ({node, ...props}) => <ul className="list-disc ml-5 mb-4 text-slate-700 space-y-1" {...props} />,
              ol: ({node, ...props}) => <ol className="list-decimal ml-5 mb-4 text-slate-700 space-y-1" {...props} />,
              li: ({node, ...props}) => <li className="pl-1" {...props} />,
              a: ({node, ...props}) => <a className="text-accent-blue hover:underline" {...props} />,
            }}
          >
            {currentReport}
          </ReactMarkdown>
        </div>
      ) : (
        <div className="bg-slate-50 rounded-lg border border-slate-200 border-dashed p-8 text-center flex flex-col items-center justify-center space-y-3 h-[300px]">
          <FileText size={32} className="text-slate-300" />
          <p className="text-sm font-semibold text-slate-700">No Clinical Report Generated</p>
          <p className="text-xs text-slate-500 max-w-xs">Click "Generate My Report" to analyze this session using the StepSense AI engine and clinical literature context.</p>
        </div>
      )}

      {hasReport && (
        <div className="flex justify-end space-x-3 pt-3 border-t border-slate-100 print:hidden">
          <button 
            onClick={handleShare}
            className="px-4 py-1.5 text-xs font-semibold border border-slate-200 rounded text-slate-600 hover:bg-slate-50 transition-colors flex items-center space-x-1"
          >
            <Share2 size={14} />
            <span>Share</span>
          </button>
          <button 
            onClick={handleExportPDF}
            className="px-4 py-1.5 text-xs font-semibold bg-slate-800 text-white rounded hover:opacity-90 transition-opacity flex items-center space-x-1"
          >
            <Download size={14} />
            <span>Export PDF</span>
          </button>
        </div>
      )}
    </div>
  );
}
